import assert from 'node:assert/strict';
import console from 'node:console';
import { readFile } from 'node:fs/promises';
import { chromium } from 'playwright';
import mysql from 'mysql2/promise';
const base = 'http://127.0.0.1:3048';
const { token } = JSON.parse(await readFile('outputs/summit-map/student-session.local', 'utf8'));
const { database, staffTokens } = JSON.parse(await readFile('outputs/passing-entry/preview-session.local', 'utf8'));
assert.equal(database, 'nukhab_guest_preview_20261021');
const pool = mysql.createPool({ host: '127.0.0.1', port: 3310, user: 'root', password: '', database });
const browser = await chromium.launch({ headless: true });
const api = async (path = '', body) => {
  const response = await globalThis.fetch(base + '/api/summit' + path, { method: body ? 'PUT' : 'GET', headers: { 'Content-Type': 'application/json', Cookie: `nukhab_session=${staffTokens.manager}` }, ...(body ? { body: JSON.stringify(body) } : {}) });
  assert.equal(response.status, 200); return response.json();
};
const original = await api('/settings');
const [[startingBalance]] = await pool.query('SELECT points,store_balance AS wallet FROM students WHERE id=11');
const createPage = async (role, session, width) => {
  const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: 'reduce', serviceWorkers: 'block' });
  await context.addCookies([{ name: 'nukhab_session', value: session, url: base, httpOnly: true, sameSite: 'Strict' }]);
  await context.addInitScript(accountRole => {
    globalThis.localStorage.setItem('wajeh_role', accountRole); globalThis.localStorage.setItem('nukhab_web_session', '1');
    globalThis.localStorage.setItem(accountRole === 'student' ? 'wajeh_student_id' : 'wajeh_supervisor_id', accountRole === 'student' ? '11' : '1');
    globalThis.localStorage.setItem('wajeh_name', accountRole === 'student' ? 'طالب الاجتياز المحلي' : 'الإدارة المحلية');
  }, role);
  const page = await context.newPage(); const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  return { context, page, errors };
};
try {
  const setup = globalThis.structuredClone(original);
  setup.mapConfig.cities[1].notificationEnabled = true;
  setup.mapConfig.cities[1].notificationText = 'وصلت إلى عنيزة محليًا';
  await api('/settings', setup);
  await pool.query('DELETE FROM student_summit_arrivals WHERE student_id=11');
  await pool.query('DELETE FROM student_summit_progress WHERE student_id=11');
  const student = await createPage('student', token, 390);
  await student.page.goto(base + '/#student/journey');
  await student.page.getByRole('dialog', { name: 'وصلت إلى عنيزة', exact: true }).waitFor();
  await student.page.getByText('وصلت إلى عنيزة محليًا', { exact: true }).waitFor();
  await student.page.route('**/api/summit/arrivals/unaizah', route => route.abort('connectionfailed'));
  await student.page.getByRole('button', { name: 'متابعة الرحلة', exact: true }).click();
  await student.page.getByRole('alert').waitFor();
  await student.page.unroute('**/api/summit/arrivals/unaizah');
  await student.page.getByRole('button', { name: 'متابعة الرحلة', exact: true }).click();
  await student.page.getByRole('dialog').waitFor({ state: 'hidden' });
  await student.page.getByRole('img', { name: `موقعك الحالي، قطعت ${Math.trunc(startingBalance.points).toLocaleString('ar-SA-u-nu-latn')} كم`, exact: true }).waitFor();
  await student.page.reload(); await student.page.locator('.qassim-map-artwork').waitFor();
  assert.equal(await student.page.getByRole('dialog').count(), 0, 'acknowledged arrival is durable');
  assert.deepEqual(student.errors, []); await student.context.close();
  const manager = await createPage('manager', staffTokens.manager, 320);
  await manager.page.goto(base + '/dashboard/settings-map');
  await manager.page.getByLabel('معاينة عند', { exact: true }).waitFor();
  await manager.page.waitForFunction(() => !globalThis.window.nukhabStartup?.active);
  await manager.page.getByLabel('معاينة عند', { exact: true }).fill('1500');
  await manager.page.getByRole('heading', { name: 'المحطات', exact: true }).locator('..').getByRole('button', { name: 'إضافة', exact: true }).click();
  await manager.page.locator('input[id^="station-"][id$="-name"]').fill('محطة المتصفح المحلية');
  await manager.page.locator('input[id^="station-"][id$="-name"]').blur();
  await manager.page.getByRole('button', { name: 'تفعيل المحطة', exact: true }).click();
  assert.equal(await manager.page.getByRole('button', { name: 'تسجيل النقاط', exact: true }).isDisabled(), true);
  const saveResponse = manager.page.waitForResponse(response => response.url().endsWith('/api/summit/settings') && response.request().method() === 'PUT');
  await manager.page.getByRole('button', { name: 'حفظ التغييرات', exact: true }).click(); assert.equal((await saveResponse).status(), 200);
  await manager.page.getByRole('button', { name: 'تسجيل النقاط', exact: true }).click();
  const dialog = manager.page.getByRole('dialog', { name: 'محطة المتصفح المحلية — تسجيل النقاط', exact: true });
  await dialog.getByLabel('نقاط طالب الاجتياز المحلي', { exact: true }).waitFor();
  await dialog.getByLabel('ابحث باسم الطالب', { exact: true }).fill('دون');
  assert.equal(await dialog.locator('input[id^="student-grade-"]:visible').count(), 1);
  await dialog.getByLabel('ابحث باسم الطالب', { exact: true }).fill('');
  await dialog.getByLabel('نقاط طالب الاجتياز المحلي', { exact: true }).fill('20');
  await manager.page.route('**/api/summit/stations/*/grades', route => route.request().method() === 'PUT' ? route.abort('connectionfailed') : route.continue());
  await dialog.getByRole('button', { name: 'حفظ', exact: true }).click(); await dialog.getByRole('alert').waitFor();
  assert.equal(await dialog.getByLabel('نقاط طالب الاجتياز المحلي', { exact: true }).inputValue(), '20');
  await manager.page.unroute('**/api/summit/stations/*/grades');
  const gradeResponse = manager.page.waitForResponse(response => response.url().includes('/grades') && response.request().method() === 'PUT');
  await dialog.getByRole('button', { name: 'حفظ', exact: true }).click(); assert.equal((await gradeResponse).status(), 200);
  assert.ok(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await manager.page.screenshot({ path: 'outputs/summit-map/station-grades-320.png', animations: 'disabled' });
  const [[balance]] = await pool.query('SELECT points,store_balance AS wallet FROM students WHERE id=11');
  assert.equal(Number(balance.points), Number(startingBalance.points) + 20); assert.equal(Number(balance.wallet), Number(startingBalance.wallet) + 20);
  await dialog.getByRole('button', { name: 'إغلاق', exact: true }).click();
  const active = await createPage('student', token, 390); await active.page.goto(base + '/#student/journey');
  await active.page.getByText('متوقف في محطة محطة المتصفح المحلية', { exact: true }).waitFor();
  await active.page.getByRole('img', { name: 'موقعك الحالي، قطعت 1,500 كم', exact: true }).waitFor();
  assert.deepEqual(manager.errors, []); assert.deepEqual(active.errors, []);
  await active.context.close(); await manager.context.close();
  console.log('Real browser flows passed: durable arrival, failed-arrival retry, create and activate station, unsaved-grade guard, roster search, failed-grade retry, ranking/store linkage and shared station stop.');
} finally {
  const current = await api('/settings'); await api('/settings', { ...original, revision: current.revision });
  await browser.close(); await pool.end();
}
